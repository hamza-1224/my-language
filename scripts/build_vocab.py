"""Turn vocab/<lang>-<level>.txt into data/frvocab.js and data/favocab.js, adding pronunciation.

Each text file: "# Topic" lines start a topic; word lines are
  French:  word | english
  Persian: word | english | everyday Hindi (alternatives split by " / ") | Hindi spelling of the shared word, if Urdu shares it
A word that already appears at a lower level is skipped. Pronunciation comes from espeak-ng:
  pip install espeakng-loader phonemizer-fork
  python3 scripts/build_vocab.py fr fa
"""
import re, json, sys, subprocess, os
sys.path.insert(0, os.path.dirname(__file__))
import pron
LEVELS = ["A1","A2","B1","B2","C1","C2"]
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = os.path.join(REPO, "vocab")

def read(lang, lvl):
    p = os.path.join(V, f"{lang}-{lvl}.txt")
    if not os.path.exists(p): return []
    topic, out = "General", []
    for line in open(p, encoding="utf-8"):
        line = line.strip()
        if not line: continue
        if line.startswith("#"): topic = line[1:].strip(); continue
        f = [x.strip() for x in line.split("|")]
        out.append((topic, f))
    return out

def speakable(w):  # what the pronunciation engine reads
    w = re.sub(r"\((m|f)\)", "", w); w = w.replace("…", "").replace("?", "").replace("؟", "").replace("!", "")
    return re.sub(r"\s+", " ", w).strip()

def build(lang):
    old = {}
    if lang == "fa":  # keep hand-written transliterations from the existing course
        old = json.loads(subprocess.check_output(["node", "-e", f'global.window=global;require("{REPO}/data/persian.js");const o={{}};for(const L of Object.values(COURSES.fa.levels))for(const v of L.vocab)o[v[0]]=v[1];console.log(JSON.stringify(o))']))
    seen, levels = set(), {}
    for lvl in LEVELS:
        rows = []
        for topic, f in read(lang, lvl):
            if f[0] in seen: continue
            seen.add(f[0]); rows.append((topic, f))
        words = [speakable(f[0]) for _, f in rows]
        prons = (pron.french if lang == "fr" else pron.persian)(words) if words else []
        lv = []
        for (topic, f), pr in zip(rows, prons):
            if lang == "fr": lv.append([f[0], f[1], pr, topic])
            else:
                tr = old.get(f[0]) or pr
                lv.append([f[0], tr, f[1], f[2] if len(f) > 2 else "", f[3] if len(f) > 3 else "", topic])
        levels[lvl] = lv
        print(lang, lvl, len(lv), file=sys.stderr)
    head = ("// Generated by scripts/build_vocab.py from the word lists in vocab/. Do not edit by hand.\n"
            + ("// [french, english, pronunciation (Devanagari, from espeak-ng), topic]\n" if lang == "fr"
               else "// [persian, transliteration, english, everyday Hindi/Urdu word (Devanagari), shared word if Persian and Urdu share one, topic]\n"))
    js = head + f"window.VOCAB = window.VOCAB || {{}};\nwindow.VOCAB.{lang} = " + json.dumps(levels, ensure_ascii=False, separators=(",", ":")).replace('],[', '],\n[') + ";\n"
    open(os.path.join(REPO, "data", f"{lang}vocab.js"), "w", encoding="utf-8").write(js)

for lang in sys.argv[1:] or ["fr", "fa"]: build(lang)
